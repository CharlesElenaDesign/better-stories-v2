#!/usr/bin/env python3
"""Generate deck-studio/templates.js from deck-studio/sample-decks/.

Run after adding or changing a sample deck:

    python3 tools/build-templates.py

Same reason as the logo pack: fetch() is blocked on file://, so the templates
ship as a plain <script> the builder injects on demand.

A template is any self-contained HTML deck in sample-decks/ that follows the
convention the three samples established:
  * :root carries --client-name, --brand-primary, --brand-accent
  * every fillable text node has data-slot="<name>"
  * sections carry data-role="cover" | "internal" | "closing"
  * the co-branded lockups are .lockup__client and .lockup__infosys
"""
import os, re, json, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC  = os.path.join(HERE, 'sample-decks')
OUT  = os.path.join(HERE, 'templates.js')

def title_of(html, fallback):
    m = re.search(r'<title>([^<]*)</title>', html)
    return (m.group(1).split('—')[0].strip() if m else fallback)

def nice(slug):
    return slug.replace('deck-', '').replace('-', ' ').strip().title()

templates = []
for f in sorted(os.listdir(SRC)):
    if not f.endswith('.html'):
        continue
    html = open(os.path.join(SRC, f), encoding='utf-8').read()
    slug = f[:-5]

    # Section roles and the slots each one owns, in document order.
    sections = []
    for m in re.finditer(r'<section\b[^>]*data-role="([^"]*)"[^>]*>', html):
        role = m.group(1)
        if role.startswith('…') or role == '':
            continue
        end = html.find('</section>', m.end())
        inner = html[m.end():end]
        slots = re.findall(r'data-slot="([^"]+)"', inner)
        sections.append({'role': role, 'slots': slots})

    # Slots outside any section (the persistent rail).
    all_slots = re.findall(r'data-slot="([^"]+)"', html)
    owned = {s for sec in sections for s in sec['slots']}
    chrome = [s for s in dict.fromkeys(all_slots) if s not in owned]

    for need in ('--client-name', '--brand-primary', '--brand-accent'):
        if need not in html:
            print(f'  !! {f} has no {need} — skipping', file=sys.stderr)
            break
    else:
        templates.append({
            'id': slug,
            'name': nice(slug),
            'sample': title_of(html, slug),
            'sections': sections,
            'chrome': chrome,
            'html': html,
        })
        print(f'  {slug:34} {len(sections)} sections, '
              f'{sum(len(s["slots"]) for s in sections)} slots + {len(chrome)} chrome')

if not templates:
    sys.exit('No usable templates found in sample-decks/.')

js = ('/* GENERATED by tools/build-templates.py — do not edit by hand.\n'
      '   Deck templates from sample-decks/, loaded on demand by index.html. */\n'
      'window.DECK_TEMPLATES = ' + json.dumps(templates, separators=(',', ':')) + ';\n')
open(OUT, 'w', encoding='utf-8').write(js)
print(f'\n{len(templates)} templates → templates.js ({len(js)/1024:.0f} KB)')
print('Bump the ?v= on TEMPLATE_PACK_SRC in index.html after regenerating.')
